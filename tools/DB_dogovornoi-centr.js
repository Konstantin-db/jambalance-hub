function makeImportedText(x, text, sourceFile=''){
  const raw = String(text || '').replace(/\r/g,'');
  let parts = raw.split(/\n+/).map(s=>s.trim()).filter(Boolean);
  if(parts.length===0) parts=['Текст импортированного документа отсутствует.'];
  const first = parts.shift();
  const blocks=[...titleBlock(first.length < 120 ? first : (x.docTypeLabel || 'ИМПОРТИРОВАННЫЙ ДОКУМЕНТ')), metaBlock(x)];
  if(sourceFile) blocks.push({type:'p', text:`Источник: ${sourceFile}`});
  if(first.length >= 120) blocks.push({type:'p', text:first});
  for(const p of parts){
    if(p.length < 80 && /^(\d+\.|[А-ЯЁ\s.,№#-]{6,})$/.test(p)) blocks.push({type:'h', text:p});
    else blocks.push({type:'p', text:p});
  }
  return blocks;
}

