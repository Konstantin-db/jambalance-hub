function relatedRecordsFor(contractIdx){
  const root=normalizeRecord(state.journal[contractIdx],contractIdx);
  const keys=contractKeys(root.contractNumber);
  return state.journal.map((record,index)=>({...normalizeRecord(record,index),_idx:index})).filter(record=>{
    if(record.recordType==='contract') return false;
    if(record.parentDocumentId&&root.id) return record.parentDocumentId===root.id;
    return keys.includes(canonicalContractNo(record.parentContractNumber));
  });
}

