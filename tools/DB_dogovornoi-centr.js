async function insertImportedRecords(records){
  const existing=new Set(state.journal.map(importRecordsSignature));
  const prepared=[];
  records.forEach((raw,index)=>{
    const record=normalizeRecord(raw,index);
    const client=findClientForRecord(record);
    if(client) record.clientId=client.id;
    record.clientSnapshot=record.clientSnapshot&&Object.keys(record.clientSnapshot).length
      ? record.clientSnapshot
      : {...clientFormData(client),clientId:client?.id||''};
    record.formData=record.formData&&Object.keys(record.formData).length
      ? record.formData
      : {...record.clientSnapshot,docType:record.docType,docDate:record.docDate,agreementNumber:record.agreementNumber||'1',parentContractNumber:record.parentContractNumber,parentContractDate:record.parentContractDate,price:record.price,newPrice:record.newPrice,newPriceDate:record.newPriceDate,reason:record.reason,specialTerms:record.specialTerms};
    const signature=importRecordsSignature(record);
    if(!existing.has(signature)){
      existing.add(signature);
      prepared.push(recordToDatabase(record,{insert:true}));
    }
  });
  for(let offset=0;offset<prepared.length;offset+=100){
    const {error}=await state.supabase.from(TABLES.documents).insert(prepared.slice(offset,offset+100));
    if(error) throw error;
  }
  await reloadDocuments();
  return prepared.length;
}

