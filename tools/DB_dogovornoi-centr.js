function findClientForRecord(record){
  const inn=digits(record.inn||record.client_inn);
  if(inn){
    const byInn=state.clients.find(client=>digits(client.inn)===inn);
    if(byInn) return byInn;
  }
  const name=String(record.clientName||record.client_name||'').trim().toLowerCase();
  return name ? state.clients.find(client=>String(client.client_name||'').trim().toLowerCase()===name)||null : null;
}

